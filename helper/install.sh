#!/bin/bash
# Install the Media Saver native-messaging host for Google Chrome (macOS, this user).
# Spec: docs/helper-protocol.md. Idempotent: every run rewrites the same three files
# and touches nothing else in the NativeMessagingHosts folder.
#
#   helper/config.json  absolute node and ffmpeg paths (Chrome starts hosts without PATH)
#   helper/host.sh      the launcher Chrome runs
#   ~/Library/Application Support/Google/Chrome/NativeMessagingHosts/com.mediasaver.helper.json
set -euo pipefail

HOST_NAME="com.mediasaver.helper"
EXTENSION_ID="ljojagcmpjloafhjikdgpdfndbncfhdc"
HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd -P)"
MANIFEST_DIR="$HOME/Library/Application Support/Google/Chrome/NativeMessagingHosts"
MANIFEST="$MANIFEST_DIR/$HOST_NAME.json"

highest_nvm_node() {
  local n v
  for n in "$HOME"/.nvm/versions/node/v*/bin/node; do
    [ -x "$n" ] || continue
    v="${n%/bin/node}"; v="${v##*/v}"
    printf '%s %s\n' "$v" "$n"
  done | sort -t. -k1,1n -k2,2n -k3,3n | tail -n 1 | cut -d' ' -f2-
}

first_executable() {
  local c
  for c in "$@"; do
    if [ -n "$c" ] && [ "${c#/}" != "$c" ] && [ -x "$c" ] && [ -f "$c" ]; then
      printf '%s\n' "$c"
      return 0
    fi
  done
  return 1
}

NODE="$(first_executable "$(command -v node || true)" /opt/homebrew/bin/node /usr/local/bin/node "$(highest_nvm_node)" || true)"
if [ -z "$NODE" ]; then
  echo "install.sh: node not found (PATH, /opt/homebrew/bin, /usr/local/bin, ~/.nvm)" >&2
  exit 1
fi
NODE_MAJOR="$("$NODE" -p 'process.versions.node.split(".")[0]')"
if [ "$NODE_MAJOR" -lt 16 ]; then
  echo "install.sh: warning: $NODE is Node $NODE_MAJOR; the helper is tested on Node 24" >&2
fi

FFMPEG="$(first_executable "$(command -v ffmpeg || true)" /opt/homebrew/bin/ffmpeg /usr/local/bin/ffmpeg || true)"
if [ -z "$FFMPEG" ]; then
  echo "install.sh: warning: ffmpeg not found; the helper will answer NO_FFMPEG until it is installed" >&2
fi

# 1. config.json (written by node so the paths are JSON-escaped correctly)
"$NODE" -e '
  const fs = require("fs");
  const [file, node, ffmpeg] = process.argv.slice(1);
  fs.writeFileSync(file, JSON.stringify({ node, ffmpeg: ffmpeg || null }, null, 2) + "\n");
' "$HERE/config.json" "$NODE" "$FFMPEG"

# 2. host.sh (written to a temp name and renamed, so a running copy is never edited in place)
{
  printf '#!/bin/bash\n'
  printf '# Generated by helper/install.sh -- re-run install.sh instead of editing.\n'
  printf '# Chrome starts native hosts without a shell PATH, so node is an absolute path.\n'
  printf 'HOST_JS=%q\n' "$HERE/host.js"
  printf 'NODE=%q\n' "$NODE"
  cat <<'EOF'
if [ -z "${HOME:-}" ]; then HOME=~; export HOME; fi
if [ ! -x "$NODE" ]; then
  NODE=""
  for c in /opt/homebrew/bin/node /usr/local/bin/node; do
    if [ -x "$c" ]; then NODE="$c"; break; fi
  done
fi
if [ -z "$NODE" ]; then
  NODE="$(for n in "$HOME"/.nvm/versions/node/v*/bin/node; do
            [ -x "$n" ] || continue
            v="${n%/bin/node}"; v="${v##*/v}"
            printf '%s %s\n' "$v" "$n"
          done | sort -t. -k1,1n -k2,2n -k3,3n | tail -n 1 | cut -d' ' -f2-)"
fi
if [ -z "$NODE" ] || [ ! -x "$NODE" ]; then
  echo "media-saver helper: node not found" >&2
  exit 1
fi
exec "$NODE" "$HOST_JS" "$@"
EOF
} > "$HERE/host.sh.tmp"
chmod 755 "$HERE/host.sh.tmp"
mv -f "$HERE/host.sh.tmp" "$HERE/host.sh"

# 3. the Chrome host manifest -- only this one file in that folder is written
mkdir -p "$MANIFEST_DIR"
"$NODE" -e '
  const fs = require("fs");
  const [file, name, hostPath, extId] = process.argv.slice(1);
  const manifest = {
    name,
    description: "Media Saver ffmpeg helper",
    path: hostPath,
    type: "stdio",
    allowed_origins: [`chrome-extension://${extId}/`],
  };
  fs.writeFileSync(file, JSON.stringify(manifest, null, 2) + "\n");
' "$MANIFEST" "$HOST_NAME" "$HERE/host.sh" "$EXTENSION_ID"

echo "node:     $NODE"
echo "ffmpeg:   ${FFMPEG:-<not found>}"
echo "host:     $HERE/host.sh"
echo "manifest: $MANIFEST"
